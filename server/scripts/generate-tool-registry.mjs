// Generates src/tools/register.generated.ts with STATIC imports of every tool,
// so the tool set can be bundled (esbuild cannot follow the runtime
// fs.readdirSync + dynamic import() used by register.ts).
//
// Re-run via `npm run bundle` (it runs this first). Drop a new tool file in
// src/tools/ that exports a `register*Tool(server)` function and it is picked up
// automatically on the next bundle.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const toolsDir = join(__dirname, "..", "src", "tools");

const EXCLUDE = new Set(["register.ts", "register.generated.ts", "index.ts"]);

const entries = [];
for (const file of readdirSync(toolsDir).sort()) {
  if (!file.endsWith(".ts") || EXCLUDE.has(file)) continue;
  const src = readFileSync(join(toolsDir, file), "utf8");
  // Match `export function registerX(` or `export async function registerX(`
  const m = src.match(/export\s+(?:async\s+)?function\s+(register[A-Za-z0-9_]*)\s*\(/);
  if (!m) {
    console.warn(`[generate-tool-registry] no register* export in ${file} — skipped`);
    continue;
  }
  entries.push({ module: "./" + file.replace(/\.ts$/, ".js"), fn: m[1] });
}

const header = `// AUTO-GENERATED by scripts/generate-tool-registry.mjs — do not edit by hand.
// Static tool registration so the server can be bundled with esbuild.
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
`;

const imports = entries.map((e) => `import { ${e.fn} } from "${e.module}";`).join("\n");
const calls = entries.map((e) => `  ${e.fn}(server);`).join("\n");

const body = `
export function registerTools(server: McpServer): void {
${calls}
}
`;

writeFileSync(join(toolsDir, "register.generated.ts"), `${header}${imports}\n${body}`, "utf8");
console.error(`[generate-tool-registry] wrote register.generated.ts with ${entries.length} tools`);
